import { inject, Injectable } from '@angular/core';
import { HttpClient, HttpParams } from '@angular/common/http';
import { Observable } from 'rxjs';

export interface PricingQuoteDTO {
  instrumentId: number;
  symbol: string;
  price: number;
  change: number;
  bid: number;
  ask: number;
  changePercent: number;
  prevClose: number;
  currency: string;
  asOf: string;
  stale: boolean;
  source: string;
}

export interface GetHoldingsResponseDTO {
  asOf: string;
  quotes: PricingQuoteDTO[];
}

// One trading day. `close` is as traded; `adjclose` is restated for splits and dividends (use it for returns).
// `synthetic` rows were generated by Fauxnance to bridge a gap in upstream data.
export interface PricingCandleDTO {
  date: string;
  open: number | null;
  high: number | null;
  low: number | null;
  close: number | null;
  adjclose: number | null;
  volume: number | null;
  synthetic: boolean;
}

// `partial` with no `asOf` and no candles means Fauxnance is still backfilling (HTTP 202); retry shortly.
export interface PricingCandlesResponseDTO {
  symbol: string;
  interval: string;
  currency: string | null;
  asOf: string | null;
  source: string | null;
  partial: boolean | null;
  availableFrom: string | null;
  candles: PricingCandleDTO[];
}

@Injectable({
  providedIn: 'root'
})
export class PricingService {
  private http = inject(HttpClient);
  private readonly apiBase = '/api/pricing';

  getQuotes(symbols: string): Observable<GetHoldingsResponseDTO> {
    const params = new HttpParams().set('symbols', symbols);
    return this.http.get<GetHoldingsResponseDTO>(`${this.apiBase}/quotes`, { params });
  }

  // Daily candles from `from` (inclusive) to today.
  getCandles(symbol: string, from: string): Observable<PricingCandlesResponseDTO> {
    const params = new HttpParams().set('from', from).set('interval', '1d');
    return this.http.get<PricingCandlesResponseDTO>(`${this.apiBase}/candles/${encodeURIComponent(symbol)}`, { params });
  }

}
